function unary()
    x = 2;  % 准备标量变量。
    y = [1, 2];  % 准备矩阵变量。
    a = +3;  % 一元正号：字面常量。
    b = +x;  % 一元正号：变量。
    c = -3;  % 一元负号：字面常量。
    d = -x;  % 一元负号：变量。
    e = ~0;  % 逻辑非：字面常量。
    f = ~x;  % 逻辑非：变量。
    g = (3).';  % 非共轭转置：字面常量。
    h = y.';  % 非共轭转置：变量。
    i = 3';  % 共轭转置：字面常量。
    j = y';  % 共轭转置：变量。
end
